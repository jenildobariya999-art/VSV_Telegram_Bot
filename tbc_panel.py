import ipaddress
def _nets(s):
    out = []
    for part in (s or "").split(","):
        part = part.strip()
        if part:
            try: out.append(ipaddress.ip_network(part, strict=False))
            except ValueError: print("ALLOWED_IPS: ignoring invalid entry %r" % part, flush=True)
    return out
